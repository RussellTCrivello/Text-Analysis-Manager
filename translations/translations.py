    def __init__(self, app: QApplication = None):
        self.app = app
        self.current_language = 'en'
        self.translator = QTranslator()
        if app:
            app.installTranslator(self.translator)
        
        # Load language from config
        try:
            from config.config_manager import ConfigManager
            config = ConfigManager()
            lang = config.get('Application', 'language', 'en')
            if lang in self.TRANSLATIONS:
                self.current_language = lang
        except:
            pass
    
    def tr(self, key: str, **kwargs) -> str:
        """Translate a key, honoring an optional fallback/default value."""
        fallback = kwargs.pop('default', None)
        if self.current_language in self.TRANSLATIONS:
            translations = self.TRANSLATIONS[self.current_language]
            if key in translations:
                text = translations[key]
                if kwargs:
                    try:
                        return text.format(**kwargs)
                    except (KeyError, IndexError, ValueError):
                        return text
                return text
        return fallback if fallback is not None else key
    
    def get_available_languages(self):
        """Get list of available language codes"""
        return list(self.TRANSLATIONS.keys())
    
    def set_language(self, language_code: str):
        """Change application language"""
        if language_code in self.TRANSLATIONS:
            self.current_language = language_code
            # Save to config
            try:
                from config.config_manager import ConfigManager
                config = ConfigManager()
                config.set('Application', 'language', language_code)
                config.save_config()
                config.save_all_to_json()
            except:
                pass
            return True
        return False
